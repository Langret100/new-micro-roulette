const assert=require('node:assert/strict');
const S=require('../inventory-core.js');
const data=S.normalizeInventory([{id:'p-a',name:'인형',limit:2,issued:0},{id:'p-b',name:'사탕',limit:null,issued:0},{id:'p-c',name:'키링',limit:1,issued:1}]);
assert.deepEqual(S.available(data).map(p=>p.name),['인형','사탕']);
assert.equal(S.award(data,'p-a'),true);
assert.equal(S.award(data,'p-a'),true);
assert.equal(S.award(data,'p-a'),false,'no further prize after sold out');
assert.equal(data[0].issued,2);
assert.deepEqual(S.available(data).map(p=>p.name),['사탕']);
assert.equal(S.award(data,'p-missing'),false);
assert.equal(S.award(data,'p-b'),true);
assert.equal(data[1].issued,1);
assert.equal(S.counts(data).issued,4);
const only=S.normalizeInventory([{name:'한정',limit:1,issued:0}]);
assert.equal(S.award(only,only[0].id),true);
assert.equal(S.available(only).length,0);
assert.equal(S.award(only,only[0].id),false);
assert.deepEqual(S.normalizeInventory([]),[],'empty reward list is supported');
assert.throws(()=>S.normalizeInventory(Array.from({length:17},(_,i)=>({name:String(i)}))));
for(const row of [{name:'X',limit:-1},{name:'X',limit:1.5},{name:'X',issued:-1},{name:'X',issued:1.8},{name:'X'.repeat(49)}])assert.throws(()=>S.normalizeInventory([row]));
const duplicates=S.normalizeInventory([{id:'p-dup',name:'젤리'},{id:'p-dup',name:'젤리'}]);
assert.equal(S.normalizeInventory([{name:'X'.repeat(48)}])[0].name.length,48,'accept longer descriptive prizes');
assert.notEqual(duplicates[0].id,duplicates[1].id,'duplicate names may be separate slots');
const cloned=JSON.parse(JSON.stringify(data));
assert.deepEqual(S.normalizeInventory(cloned),data,'persisted inventory survives round trip');
console.log('PASS: stock normalization, unique ids, exact quotas, unlimited, all sold out, persistence, input rejection');

const gradeLines='1|사탕|10\n3|키링|2\n4|전설상품|';
const parsed=S.parseRewardText(gradeLines);
assert.deepEqual(parsed.map(x=>x.grade),[1,3,4]);
assert.equal(parsed[2].limit,null);
assert.equal(S.parseRewardText('# 빈 명단\n\n').length,0);
assert.throws(()=>S.parseRewardText('5|오류|1'));
assert.equal(S.parseRewardText(S.toRewardText(parsed)).length,3);
console.log('PASS: graded reward TXT import/export / blank TXT / stock validation');
